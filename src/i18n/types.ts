/* =========================================================
   国际化类型定义
   ========================================================= */

/** 支持的语言：英文 / 中文 */
export type Lang = 'en' | 'zh'

/**
 * 双语值。`en` 为原文基准，`zh` 可选 —— 缺失时自动回退到 `en`，
 * 这样逐块铺开翻译时，未翻译的内容只会显示英文，不会变空白。
 */
export type Bi<T = string> = { en: T; zh?: T }

/**
 * 可本地化值。
 * - 直接传 `T`：表示两种语言共用（如纯数字、技术名词、缩写）
 * - 传 `Bi<T>`：表示该字段有独立的中英两版
 */
export type Localized<T = string> = T | Bi<T>
